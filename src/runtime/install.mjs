async function removeEmptyParents(projectRoot, absolutePath) {
  let current = path.dirname(absolutePath);
  while (
    current !== projectRoot &&
    current.startsWith(`${projectRoot}${path.sep}`)
  ) {
    const entries = await fs.readdir(current).catch(() => null);
    if (!entries || entries.length > 0) break;
    await fs.rmdir(current).catch(() => {});
    current = path.dirname(current);
  }
}

async function writeTransactionJournal(projectRoot, journal) {
  await atomicWrite(
    path.join(projectRoot, transactionRelativePath),
    jsonText(journal),
  );
}

async function rollbackTransaction(projectRoot, journal) {
  const rollbackErrors = [];
  for (const backup of [...journal.backups].reverse()) {
    let absolutePath;
    try {
      if (
        typeof backup.path !== 'string' ||
        (backup.content !== null && typeof backup.content !== 'string')
      ) {
        throw new Error('Transaction backup entry is invalid');
      }
      absolutePath = resolveProjectPath(
        projectRoot,
        backup.path,
        'transaction backup path',
      );
      if (backup.content === null) {
        await fs.rm(absolutePath, { force: true });
        await removeEmptyParents(projectRoot, absolutePath);
      } else {
        await atomicWrite(absolutePath, backup.content);
      }
    } catch (error) {
      rollbackErrors.push(`${backup.path}: ${error.message}`);
    }
  }
  if (rollbackErrors.length > 0) {
    throw new DesignomeError('Installation rollback was incomplete', {
      code: 'INSTALLATION_ROLLBACK_FAILED',
      details: rollbackErrors,
    });
  }
}

export async function recoverInterruptedInstallation({ projectPath }) {
  const projectRoot = await assertProjectRoot(projectPath);
  const journalPath = path.join(projectRoot, transactionRelativePath);
  if (!(await pathExists(journalPath))) {
    return { status: 'not-required', recovered: false };
  }
  let journal;
  try {
    journal = await readJson(journalPath);
  } catch (error) {
    throw new DesignomeError('Interrupted installation journal is unreadable', {
      code: 'INSTALLATION_JOURNAL_UNREADABLE',
      details: [error.message],
    });
  }
  if (journal.schemaVersion !== '1.0.0' || !Array.isArray(journal.backups)) {
    throw new DesignomeError(
      'Interrupted installation journal is incompatible',
      {
        code: 'INSTALLATION_JOURNAL_INCOMPATIBLE',
        details: { schemaVersion: journal.schemaVersion ?? null },
      },
    );
  }
  if (journal.owner !== 'designome') {
    throw new DesignomeError(
      'Interrupted installation journal owner is invalid',
      {
        code: 'INSTALLATION_JOURNAL_INCOMPATIBLE',
        details: { owner: journal.owner ?? null },
      },
    );
  }
  await rollbackTransaction(projectRoot, journal);
  await fs.rm(journalPath, { force: true });
  await removeEmptyParents(projectRoot, journalPath);
  return {
    status: 'recovered',
    recovered: true,
    transactionId: journal.transactionId,
    restoredArtifactCount: journal.backups.length,
  };
}

async function prepareInstallation(plan, writeActions, transactionId) {
  const stagingDirectory = await fs.mkdtemp(
    path.join(os.tmpdir(), `designome-install-${transactionId}-`),
  );
  const prepared = [];
  try {
    for (const [index, action] of writeActions.entries()) {
      if (action.action === 'delete') {
        prepared.push({ ...action, stagedPath: null });
        continue;
      }
      const stagedPath = path.join(stagingDirectory, String(index));
      await atomicWrite(stagedPath, action.content);
      const stagedContent = await fs.readFile(stagedPath, 'utf8');
      if (stagedContent !== action.content) {
        throw new DesignomeError(
          'Prepared installation artifact failed validation',
          {
            code: 'INSTALLATION_PREPARATION_INVALID',
            details: { path: action.path },
          },
        );
      }
      prepared.push({ ...action, stagedPath });
    }
    return { stagingDirectory, prepared };
  } catch (error) {
    await fs.rm(stagingDirectory, { force: true, recursive: true });
    throw error;
  }
}

async function assertPlanStillCurrent(projectRoot, action) {
  const absolutePath = path.join(projectRoot, action.path);
  const current = await readTextIfExists(absolutePath);
  const observed = current === null ? null : sha256(current);
  if (observed !== (action.observedChecksum ?? null)) {
    throw new DesignomeError('Target changed after installation planning', {
      code: 'INSTALLATION_PLAN_STALE',
      details: {
        path: action.path,
        plannedChecksum: action.observedChecksum ?? null,
        observedChecksum: observed,
        refusedOperations: [action.action],
        resolution: 'Run a new diagnostic and dry-run before retrying.',
      },
    });
  }
}

async function verifyAppliedActions(projectRoot, actions) {
  const errors = [];
  for (const action of actions) {
    const absolutePath = path.join(projectRoot, action.path);
    const current = await readTextIfExists(absolutePath);
    if (action.action === 'delete') {
      if (current !== null) errors.push(`${action.path} was not deleted`);
    } else if (current !== action.content) {
      errors.push(`${action.path} does not match its prepared content`);
    }
  }
  if (errors.length > 0) {
    throw new DesignomeError(
      'Applied installation files failed validation before manifest commit',
      {
        code: 'INSTALLATION_APPLY_VERIFICATION_FAILED',
        details: errors,
      },
    );
  }
}

export async function planInstallation({
  dnaPath,
  projectPath,
  cssEntry,
  scope = ':root',
  documentationDirectory = defaultDocumentationDirectory,
  rulePrecedence = 'complement',
  existingRulePaths = [],
  stylingStrategy = 'auto',
  uiKitPreference = 'auto',
  instructionsReviewed = false,
}) {
  if (![':root', '[data-designome]'].includes(scope)) {
    throw new DesignomeError(
      'CSS scope must be either :root or [data-designome]',
      { code: 'INVALID_CSS_SCOPE' },
    );
  }
  if (
    !['complement', 'existing-first', 'designome-first'].includes(
      rulePrecedence,
    )
  ) {
    throw new DesignomeError(
      'Rule precedence must be complement, existing-first, or designome-first',
      {
        code: 'INVALID_RULE_PRECEDENCE',
      },
    );
  }
  if (!['auto', 'none', 'shadcn'].includes(uiKitPreference)) {
    throw new DesignomeError(
      'UI kit preference must be auto, none, or shadcn',
      { code: 'INVALID_UI_KIT_PREFERENCE' },
    );
  }
  if (
    ![
      'auto',
      'css-variables',
      'tailwind-utilities',
      'shadcn-components',
    ].includes(stylingStrategy)
  ) {
    throw new DesignomeError(
      'Styling strategy must be auto, css-variables, tailwind-utilities, or shadcn-components',
      {
        code: 'INVALID_STYLE_STRATEGY',
      },
    );
  }

  const projectRoot = await assertProjectRoot(projectPath);
  await assertManagedDirectorySafe(projectRoot);
  const resolvedDnaPath = path.resolve(dnaPath);
  const dna = await readJson(resolvedDnaPath).catch((error) => {
    throw new DesignomeError(`Cannot read Design DNA: ${resolvedDnaPath}`, {
      code: 'DESIGN_DNA_UNREADABLE',
      details: [error.message],
    });
  });
  await assertValidDesignDna(dna, { requireAccepted: true });
  const conceptMatrix = await readJson(
    path.join(pluginRoot, 'concepts', 'concept-matrix.v0.2.json'),
  );

  const resolvedCssEntry = await resolveCssEntry(projectRoot, cssEntry);
  const cssEntryRelative = toPosixPath(
    relativeInside(projectRoot, resolvedCssEntry, 'CSS entry'),
  );
  const cssDirectory = path.dirname(resolvedCssEntry);
  const resolvedDocumentationDirectory = resolveProjectPath(
    projectRoot,
    documentationDirectory,
    '--docs-dir',
  );
  const documentationRelative = toPosixPath(
    relativeInside(projectRoot, resolvedDocumentationDirectory, '--docs-dir'),
  );
  if (
    !documentationRelative ||
    documentationRelative === '.' ||
    documentationRelative.startsWith('.designome')
  ) {
    throw new DesignomeError(
      'Documentation directory must be a visible project-relative directory outside .designome',
      {
        code: 'INVALID_DOCUMENTATION_DIRECTORY',
      },
    );
  }
  const normalizedExistingRulePaths = [];
  for (const rulePath of existingRulePaths) {
    const absoluteRulePath = resolveProjectPath(
      projectRoot,
      rulePath,
      '--existing-rules',
    );
    if (!(await pathExists(absoluteRulePath))) {
      throw new DesignomeError(
        `Declared existing rule path does not exist: ${rulePath}`,
        {
          code: 'EXISTING_RULE_PATH_MISSING',
        },
      );
    }
    normalizedExistingRulePaths.push(
      toPosixPath(
        relativeInside(
          projectRoot,
          await fs.realpath(absoluteRulePath),
          '--existing-rules',
        ),
      ),
    );
  }
  const styling = await detectStylingContext(
    projectRoot,
    resolvedCssEntry,
    stylingStrategy,
    uiKitPreference,
  );
  const integrationPolicy = {
    documentationLayout: 'complete-v1',
    rulePrecedence,
    existingRulePaths: [...new Set(normalizedExistingRulePaths)].sort(),
    uiKitPreference,
  };
  const generatedCssPath = path.join(cssDirectory, 'designome.generated.css');
  const overridesCssPath = path.join(cssDirectory, 'designome.overrides.css');
  if (
    resolvedCssEntry === generatedCssPath ||
    resolvedCssEntry === overridesCssPath
  ) {
    throw new DesignomeError(
      'The CSS entry cannot be a Designome-managed CSS file',
      {
        code: 'INVALID_CSS_ENTRY',
      },
    );
  }

  const generatedCssRelative = toPosixPath(
    relativeInside(projectRoot, generatedCssPath),
  );
  const overridesCssRelative = toPosixPath(
    relativeInside(projectRoot, overridesCssPath),
  );
  const agentsRelative = 'AGENTS.md';
  const manifestPath = path.join(projectRoot, manifestRelativePath);
  const previousManifest = (await pathExists(manifestPath))
    ? await readJson(manifestPath)
    : null;
  if (
    previousManifest &&
    !supportedManifestVersions.has(previousManifest.schemaVersion)
  ) {
    throw new DesignomeError('Installed manifest version is unsupported', {
      code: 'UNSUPPORTED_MANIFEST',
    });
  }

  const generatedCss = renderGeneratedCss(dna, scope, styling);
  const dnaText = jsonText(dna);
  const importBlock = renderCssImportBlock(
    path.basename(generatedCssPath),
    path.basename(overridesCssPath),
  );
  const guidanceBlock = renderGuidanceBlock({
    documentationDirectory: documentationRelative,
    integrationPolicy,
    styling,
  });
  const documentation = renderDocumentation({
    dna,
    styling,
    integrationPolicy,
    documentationDirectory: documentationRelative,
    matrix: conceptMatrix,
  });
  const auditSkill = new Map([
    [
      'SKILL.md',
      await fs.readFile(
        path.join(pluginRoot, 'skills', 'designome-audit', 'SKILL.md'),
        'utf8',
      ),
    ],
    [
      'agents/openai.yaml',
      await fs.readFile(
        path.join(
          pluginRoot,
          'skills',
          'designome-audit',
          'agents',
          'openai.yaml',
        ),
        'utf8',
      ),
    ],
    [
      'contract.json',
      await fs.readFile(
        path.join(pluginRoot, 'skills', 'designome-audit', 'contract.json'),
        'utf8',
      ),
    ],
  ]);
  const instructionFiles = await discoverInstructionFiles(
    projectRoot,
    resolvedCssEntry,
  );

  const actions = [];
  actions.push(
    await inspectOwnedFile(
      projectRoot,
      installedDnaRelativePath,
      dnaText,
      previousManifest,
    ),
  );
  for (const [filename, content] of documentation) {
    actions.push(
      await inspectOwnedFile(
        projectRoot,
        toPosixPath(path.join(documentationRelative, filename)),
        content,
        previousManifest,
      ),
    );
  }
  const desiredDocumentationPaths = new Set(
    [...documentation.keys()].map((filename) =>
      toPosixPath(path.join(documentationRelative, filename)),
    ),
  );
  actions.push(
    ...(await inspectObsoleteDocumentationFiles({
      projectRoot,
      previousManifest,
      documentationRelative,
      desiredPaths: desiredDocumentationPaths,
    })),
  );
  for (const [filename, content] of auditSkill) {
    actions.push(
      await inspectOwnedFile(
        projectRoot,
        toPosixPath(path.join(auditSkillRelativeDirectory, filename)),
        content,
        previousManifest,
      ),
    );
  }
  actions.push(
    await inspectOwnedFile(
      projectRoot,
      generatedCssRelative,
      generatedCss,
      previousManifest,
    ),
  );
  actions.push(
    await inspectBlockFile({
      projectRoot,
      relativePath: cssEntryRelative,
      desiredBlock: importBlock,
      startMarker: cssStartMarker,
      endMarker: cssEndMarker,
      placement: 'css-top',
      previousManifest,
    }),
  );
  actions.push(
    await inspectBlockFile({
      projectRoot,
      relativePath: agentsRelative,
      desiredBlock: guidanceBlock,
      startMarker: guidanceStartMarker,
      endMarker: guidanceEndMarker,
      placement: 'append',
      previousManifest,
    }),
  );

  const overridesCurrent = await readTextIfExists(overridesCssPath);
  actions.push({
    path: overridesCssRelative,
    kind: 'user-owned',
    action: overridesCurrent === null ? 'create' : 'preserve',
    content: overridesCurrent === null ? renderOverridesCss() : null,
    observedChecksum:
      overridesCurrent === null ? null : sha256(overridesCurrent),
  });
  const auditConfigPath = path.join(projectRoot, auditConfigRelativePath);
  const auditConfigCurrent = await readTextIfExists(auditConfigPath);
  actions.push({
    path: auditConfigRelativePath,
    kind: 'user-owned',
    action: auditConfigCurrent === null ? 'create' : 'preserve',
    content: auditConfigCurrent === null ? renderAuditConfig() : null,
    observedChecksum:
      auditConfigCurrent === null ? null : sha256(auditConfigCurrent),
  });

  const conflicts = actions.filter((action) => action.action === 'conflict');
  const packageJson = await readJson(path.join(pluginRoot, 'package.json'));
  const dnaHash = sha256(dnaText);
  const configurationFingerprint = sha256(
    jsonText({
      dnaHash,
      cssEntryRelative,
      generatedCssRelative,
      overridesCssRelative,
      scope,
      documentationRelative,
      documentationLayoutVersion: conceptMatrix.documentationLayoutVersion,
      integrationPolicy,
      styling,
    }),
  );
  const installedAt =
    previousManifest?.configurationFingerprint === configurationFingerprint
      ? previousManifest.installedAt
      : new Date().toISOString();

  const managedArtifacts = actions
    .filter((action) => action.kind === 'file' || action.kind === 'block')
    .filter(
      (action) => action.action !== 'conflict' && action.action !== 'delete',
    )
    .map((action) =>
      action.kind === 'file'
        ? { path: action.path, kind: 'file', sha256: action.sha256 }
        : {
            path: action.path,
            kind: 'block',
            sha256: action.blockSha256,
            startMarker: action.startMarker,
            endMarker: action.endMarker,
          },
    );
  const manifest = {
    schemaVersion: '0.2.0',
    pluginVersion: packageJson.version,
    installedAt,
    configurationFingerprint,
    dna: {
      documentId: dna.documentId,
      revision: dna.revision.number,
      sha256: dnaHash,
    },
    adapter: {
      cssEntry: cssEntryRelative,
      generatedCss: generatedCssRelative,
      overridesCss: overridesCssRelative,
      scope,
      documentationDirectory: documentationRelative,
      documentationLayoutVersion: conceptMatrix.documentationLayoutVersion,
      styling,
      integrationPolicy,
      instructionFiles,
      instructionsReviewed:
        instructionsReviewed ||
        previousManifest?.adapter?.instructionsReviewed === true,
    },
    managedArtifacts,
    userOwnedArtifacts: [
      { path: overridesCssRelative, kind: 'file', rewritePolicy: 'preserve' },
      {
        path: auditConfigRelativePath,
        kind: 'file',
        rewritePolicy: 'preserve',
      },
    ],
  };
  const manifestText = jsonText(manifest);
  const currentManifestText = await readTextIfExists(manifestPath);
  const manifestAction = {
    path: manifestRelativePath,
    kind: 'manifest',
    action:
      conflicts.length > 0
        ? 'blocked'
        : currentManifestText === null
          ? 'create'
          : currentManifestText === manifestText
            ? 'unchanged'
            : 'update',
    content: manifestText,
    observedChecksum:
      currentManifestText === null ? null : sha256(currentManifestText),
  };
  actions.push(manifestAction);

  return {
    status: conflicts.length > 0 ? 'conflict' : 'ready',
    projectRoot,
    dnaPath: resolvedDnaPath,
    dna,
    manifest,
    actions,
    publicPlan: {
      status: conflicts.length > 0 ? 'conflict' : 'ready',
      dna: manifest.dna,
      adapter: manifest.adapter,
      actions: actions.map(publicAction),
      conflictCount: conflicts.length,
      transaction: {
        schemaVersion: '1.0.0',
        phases: [
          'diagnostic',
          'preflight',
          'plan',
          'prepare',
          'validate-prepared',
          'apply',
          'verify',
          'commit-manifest',
          'cleanup',
        ],
        manifestWrittenLast: true,
        rollbackOnFailure: true,
      },
    },
  };
}

export async function installDesignDna(options) {
  const transactionPath = path.join(
    path.resolve(options.projectPath),
    transactionRelativePath,
  );
  const recovery = options.dryRun
    ? {
        status: (await pathExists(transactionPath))
          ? 'recovery-required'
          : 'not-required',
        recovered: false,
        readOnly: true,
      }
    : await recoverInterruptedInstallation({
        projectPath: options.projectPath,
      });
  const plan = await planInstallation(options);
  if (plan.status === 'conflict' || options.dryRun) {
    return { ...plan.publicPlan, recovery };
  }
  if (!options.instructionsReviewed) {
    throw new DesignomeError(
      'Writing requires --instructions-reviewed after the dry-run and instruction review',
      {
        code: 'INSTRUCTIONS_NOT_REVIEWED',
      },
    );
  }

  const writeActions = plan.actions.filter((action) =>
    ['create', 'update', 'delete'].includes(action.action),
  );
  const transactionId = randomUUID();
  let prepared;
  try {
    if (options.failureInjection === 'prepare') {
      throw new Error('Injected preparation failure');
    }
    prepared = await prepareInstallation(plan, writeActions, transactionId);
  } catch (error) {
    throw new DesignomeError(
      'Installation preparation failed before target writes',
      {
        code: 'INSTALLATION_PREPARATION_FAILED',
        details: {
          cause: error.message,
          projectModified: false,
          transactionId,
        },
      },
    );
  }

  const journal = {
    schemaVersion: '1.0.0',
    transactionId,
    owner: 'designome',
    projectRoot: plan.projectRoot,
    createdAt: new Date().toISOString(),
    status: 'applying',
    currentAction: null,
    backups: [],
  };
  try {
    await writeTransactionJournal(plan.projectRoot, journal);
    const appliedBeforeManifest = [];
    for (const [index, action] of prepared.prepared.entries()) {
      const absolutePath = path.join(plan.projectRoot, action.path);
      if (action.kind === 'manifest') {
        journal.status = 'verifying-before-manifest';
        await writeTransactionJournal(plan.projectRoot, journal);
        await verifyAppliedActions(plan.projectRoot, appliedBeforeManifest);
        journal.status = 'committing-manifest';
        await writeTransactionJournal(plan.projectRoot, journal);
      }
      await assertPlanStillCurrent(plan.projectRoot, action);
      journal.currentAction = action.path;
      journal.backups.push({
        path: action.path,
        content: await readTextIfExists(absolutePath),
      });
      await writeTransactionJournal(plan.projectRoot, journal);
      if (options.failureInjection === 'apply' && index === 1) {
        throw new Error('Injected application failure');
      }
      if (action.action === 'delete') {
        await fs.rm(absolutePath, { force: true });
      } else {
        await atomicWrite(
          absolutePath,
          await fs.readFile(action.stagedPath, 'utf8'),
        );
      }
      if (action.kind !== 'manifest') appliedBeforeManifest.push(action);
    }
  } catch (error) {
    await rollbackTransaction(plan.projectRoot, journal);
    await fs.rm(path.join(plan.projectRoot, transactionRelativePath), {
      force: true,
    });
    await removeEmptyParents(
      plan.projectRoot,
      path.join(plan.projectRoot, transactionRelativePath),
    );
    throw new DesignomeError(
      'Installation failed and completed writes were rolled back',
      {
        code: 'INSTALLATION_ROLLED_BACK',
        details: {
          cause: error.message,
          transactionId,
          rollback: 'completed',
          projectModified: false,
        },
      },
    );
  } finally {
    await fs.rm(prepared.stagingDirectory, { force: true, recursive: true });
  }

  const verification = await verifyInstallation({
    projectPath: plan.projectRoot,
  });
  if (!verification.valid) {
    await rollbackTransaction(plan.projectRoot, journal);
    await fs.rm(path.join(plan.projectRoot, transactionRelativePath), {
      force: true,
    });
    await removeEmptyParents(
      plan.projectRoot,
      path.join(plan.projectRoot, transactionRelativePath),
    );
    throw new DesignomeError(
      'Post-install verification failed and installation was rolled back',
      {
        code: 'POST_INSTALL_VERIFICATION_FAILED',
        details: {
          verificationErrors: verification.errors,
          transactionId,
          rollback: 'completed',
          projectModified: false,
        },
      },
    );
  }

  await fs.rm(path.join(plan.projectRoot, transactionRelativePath), {
    force: true,
  });

  return {
    ...plan.publicPlan,
    status: 'installed',
    verification: 'passed',
    recovery,
    transaction: {
      ...plan.publicPlan.transaction,
      transactionId,
      status: 'committed',
      preparedArtifactCount: writeActions.length,
      appliedArtifactCount: writeActions.length,
      rollback: 'not-required',
    },
  };
}

export async function verifyInstallation({ projectPath }) {
  const projectRoot = await assertProjectRoot(projectPath);
  await assertManagedDirectorySafe(projectRoot);
  const errors = [];
  const manifestPath = path.join(projectRoot, manifestRelativePath);
  if (!(await pathExists(manifestPath))) {
    return {
      valid: false,
      projectRoot,
      errors: ['.designome/manifest.json is missing'],
    };
  }

  let manifest;
  try {
    manifest = await readJson(manifestPath);
  } catch (error) {
    return {
      valid: false,
      projectRoot,
      errors: [`Cannot parse manifest: ${error.message}`],
    };
  }
  if (!supportedManifestVersions.has(manifest.schemaVersion))
    errors.push('Unsupported manifest schemaVersion');

  for (const artifact of manifest.managedArtifacts ?? []) {
    let absolutePath;
    try {
      absolutePath = resolveProjectPath(
        projectRoot,
        artifact.path,
        'managed artifact path',
      );
    } catch (error) {
      errors.push(`Unsafe managed artifact path: ${String(artifact.path)}`);
      continue;
    }
    const content = await readTextIfExists(absolutePath);
    if (content === null) {
      errors.push(`Managed artifact is missing: ${artifact.path}`);
      continue;
    }
    if (artifact.kind === 'file') {
      if (sha256(content) !== artifact.sha256)
        errors.push(`Managed file checksum mismatch: ${artifact.path}`);
      continue;
    }
    if (artifact.kind === 'block') {
      const block = inspectManagedBlock(
        content,
        artifact.startMarker,
        artifact.endMarker,
      );
      if (
        block.startCount !== 1 ||
        block.endCount !== 1 ||
        block.block === null
      ) {
        errors.push(
          `Managed block markers are missing or duplicated: ${artifact.path}`,
        );
      } else if (sha256(block.block) !== artifact.sha256) {
        errors.push(`Managed block checksum mismatch: ${artifact.path}`);
      }
    }
  }

  for (const artifact of manifest.userOwnedArtifacts ?? []) {
    let absolutePath;
    try {
      absolutePath = resolveProjectPath(
        projectRoot,
        artifact.path,
        'user-owned artifact path',
      );
    } catch (error) {
      errors.push(`Unsafe user-owned artifact path: ${String(artifact.path)}`);
      continue;
    }
    if (!(await pathExists(absolutePath))) {
      errors.push(`User-owned override artifact is missing: ${artifact.path}`);
    }
  }

  const installedDnaPath = path.join(projectRoot, installedDnaRelativePath);
  if (await pathExists(installedDnaPath)) {
    try {
      const dna = await readJson(installedDnaPath);
      errors.push(
        ...(await validateDesignDna(dna, { requireAccepted: true })).map(
          (error) => `Design DNA: ${error}`,
        ),
      );
      if (sha256(jsonText(dna)) !== manifest.dna?.sha256)
        errors.push('Installed Design DNA does not match manifest DNA hash');
    } catch (error) {
      errors.push(`Cannot validate installed Design DNA: ${error.message}`);
    }
  }

  return {
    valid: errors.length === 0,
    projectRoot,
    documentId: manifest.dna?.documentId ?? null,
    revision: manifest.dna?.revision ?? null,
    managedArtifactCount: manifest.managedArtifacts?.length ?? 0,
    errors,
  };
}
