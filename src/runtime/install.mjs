export async function planInstallation({
  dnaPath,
  projectPath,
  cssEntry,
  scope = ':root',
  instructionsReviewed = false,
}) {
  if (![':root', '[data-designome]'].includes(scope)) {
    throw new DesignomeError(
      'CSS scope must be either :root or [data-designome]',
      { code: 'INVALID_CSS_SCOPE' },
    );
  }

  const projectRoot = await assertProjectRoot(projectPath);
  await assertManagedDirectorySafe(projectRoot);
  const resolvedDnaPath = path.resolve(dnaPath);
  const dna = await readJson(resolvedDnaPath).catch((error) => {
    throw new DesignomeError(`Cannot read Design DNA: ${resolvedDnaPath}`, {
      code: 'DESIGN_DNA_UNREADABLE',
      details: [error.message],
    });
  });
  await assertValidDesignDna(dna, { requireAccepted: true });

  const resolvedCssEntry = await resolveCssEntry(projectRoot, cssEntry);
  const cssEntryRelative = toPosixPath(
    relativeInside(projectRoot, resolvedCssEntry, 'CSS entry'),
  );
  const cssDirectory = path.dirname(resolvedCssEntry);
  const generatedCssPath = path.join(cssDirectory, 'designome.generated.css');
  const overridesCssPath = path.join(cssDirectory, 'designome.overrides.css');
  if (
    resolvedCssEntry === generatedCssPath ||
    resolvedCssEntry === overridesCssPath
  ) {
    throw new DesignomeError(
      'The CSS entry cannot be a Designome-managed CSS file',
      {
        code: 'INVALID_CSS_ENTRY',
      },
    );
  }

  const generatedCssRelative = toPosixPath(
    relativeInside(projectRoot, generatedCssPath),
  );
  const overridesCssRelative = toPosixPath(
    relativeInside(projectRoot, overridesCssPath),
  );
  const agentsRelative = 'AGENTS.md';
  const manifestPath = path.join(projectRoot, manifestRelativePath);
  const previousManifest = (await pathExists(manifestPath))
    ? await readJson(manifestPath)
    : null;
  if (previousManifest && previousManifest.schemaVersion !== '0.1.0') {
    throw new DesignomeError('Installed manifest version is unsupported', {
      code: 'UNSUPPORTED_MANIFEST',
    });
  }

  const generatedCss = renderGeneratedCss(dna, scope);
  const dnaText = jsonText(dna);
  const importBlock = renderCssImportBlock(
    path.basename(generatedCssPath),
    path.basename(overridesCssPath),
  );
  const guidanceBlock = renderGuidanceBlock();
  const instructionFiles = await discoverInstructionFiles(
    projectRoot,
    resolvedCssEntry,
  );

  const actions = [];
  actions.push(
    await inspectOwnedFile(
      projectRoot,
      installedDnaRelativePath,
      dnaText,
      previousManifest,
    ),
  );
  actions.push(
    await inspectOwnedFile(
      projectRoot,
      generatedCssRelative,
      generatedCss,
      previousManifest,
    ),
  );
  actions.push(
    await inspectBlockFile({
      projectRoot,
      relativePath: cssEntryRelative,
      desiredBlock: importBlock,
      startMarker: cssStartMarker,
      endMarker: cssEndMarker,
      placement: 'css-top',
      previousManifest,
    }),
  );
  actions.push(
    await inspectBlockFile({
      projectRoot,
      relativePath: agentsRelative,
      desiredBlock: guidanceBlock,
      startMarker: guidanceStartMarker,
      endMarker: guidanceEndMarker,
      placement: 'append',
      previousManifest,
    }),
  );

  const overridesCurrent = await readTextIfExists(overridesCssPath);
  actions.push({
    path: overridesCssRelative,
    kind: 'user-owned',
    action: overridesCurrent === null ? 'create' : 'preserve',
    content: overridesCurrent === null ? renderOverridesCss() : null,
  });

  const conflicts = actions.filter((action) => action.action === 'conflict');
  const packageJson = await readJson(path.join(pluginRoot, 'package.json'));
  const dnaHash = sha256(dnaText);
  const configurationFingerprint = sha256(
    jsonText({
      dnaHash,
      cssEntryRelative,
      generatedCssRelative,
      overridesCssRelative,
      scope,
    }),
  );
  const installedAt =
    previousManifest?.configurationFingerprint === configurationFingerprint
      ? previousManifest.installedAt
      : new Date().toISOString();

  const managedArtifacts = actions
    .filter((action) => action.kind === 'file' || action.kind === 'block')
    .filter((action) => action.action !== 'conflict')
    .map((action) =>
      action.kind === 'file'
        ? { path: action.path, kind: 'file', sha256: action.sha256 }
        : {
            path: action.path,
            kind: 'block',
            sha256: action.blockSha256,
            startMarker: action.startMarker,
            endMarker: action.endMarker,
          },
    );
  const manifest = {
    schemaVersion: '0.1.0',
    pluginVersion: packageJson.version,
    installedAt,
    configurationFingerprint,
    dna: {
      documentId: dna.documentId,
      revision: dna.revision.number,
      sha256: dnaHash,
    },
    adapter: {
      cssEntry: cssEntryRelative,
      generatedCss: generatedCssRelative,
      overridesCss: overridesCssRelative,
      scope,
      instructionFiles,
      instructionsReviewed:
        instructionsReviewed ||
        previousManifest?.adapter?.instructionsReviewed === true,
    },
    managedArtifacts,
    userOwnedArtifacts: [
      { path: overridesCssRelative, kind: 'file', rewritePolicy: 'preserve' },
    ],
  };
  const manifestText = jsonText(manifest);
  const currentManifestText = await readTextIfExists(manifestPath);
  const manifestAction = {
    path: manifestRelativePath,
    kind: 'manifest',
    action:
      conflicts.length > 0
        ? 'blocked'
        : currentManifestText === null
          ? 'create'
          : currentManifestText === manifestText
            ? 'unchanged'
            : 'update',
    content: manifestText,
  };
  actions.push(manifestAction);

  return {
    status: conflicts.length > 0 ? 'conflict' : 'ready',
    projectRoot,
    dnaPath: resolvedDnaPath,
    dna,
    manifest,
    actions,
    publicPlan: {
      status: conflicts.length > 0 ? 'conflict' : 'ready',
      dna: manifest.dna,
      adapter: manifest.adapter,
      actions: actions.map(publicAction),
      conflictCount: conflicts.length,
    },
  };
}

export async function installDesignDna(options) {
  const plan = await planInstallation(options);
  if (plan.status === 'conflict' || options.dryRun) return plan.publicPlan;
  if (!options.instructionsReviewed) {
    throw new DesignomeError(
      'Writing requires --instructions-reviewed after the dry-run and instruction review',
      {
        code: 'INSTRUCTIONS_NOT_REVIEWED',
      },
    );
  }

  const writeActions = plan.actions.filter((action) =>
    ['create', 'update'].includes(action.action),
  );
  const backups = [];
  try {
    for (const action of writeActions) {
      const absolutePath = path.join(plan.projectRoot, action.path);
      backups.push({
        path: absolutePath,
        content: await readTextIfExists(absolutePath),
      });
      await atomicWrite(absolutePath, action.content);
    }
  } catch (error) {
    await rollbackWrites(backups);
    throw new DesignomeError(
      'Installation failed and completed writes were rolled back',
      {
        code: 'INSTALLATION_ROLLED_BACK',
        details: [error.message],
      },
    );
  }

  const verification = await verifyInstallation({
    projectPath: plan.projectRoot,
  });
  if (!verification.valid) {
    await rollbackWrites(backups);
    throw new DesignomeError(
      'Post-install verification failed and installation was rolled back',
      {
        code: 'POST_INSTALL_VERIFICATION_FAILED',
        details: verification.errors,
      },
    );
  }

  return {
    ...plan.publicPlan,
    status: 'installed',
    verification: 'passed',
  };
}

export async function verifyInstallation({ projectPath }) {
  const projectRoot = await assertProjectRoot(projectPath);
  await assertManagedDirectorySafe(projectRoot);
  const errors = [];
  const manifestPath = path.join(projectRoot, manifestRelativePath);
  if (!(await pathExists(manifestPath))) {
    return {
      valid: false,
      projectRoot,
      errors: ['.designome/manifest.json is missing'],
    };
  }

  let manifest;
  try {
    manifest = await readJson(manifestPath);
  } catch (error) {
    return {
      valid: false,
      projectRoot,
      errors: [`Cannot parse manifest: ${error.message}`],
    };
  }
  if (manifest.schemaVersion !== '0.1.0')
    errors.push('Unsupported manifest schemaVersion');

  for (const artifact of manifest.managedArtifacts ?? []) {
    let absolutePath;
    try {
      absolutePath = resolveProjectPath(
        projectRoot,
        artifact.path,
        'managed artifact path',
      );
    } catch (error) {
      errors.push(`Unsafe managed artifact path: ${String(artifact.path)}`);
      continue;
    }
    const content = await readTextIfExists(absolutePath);
    if (content === null) {
      errors.push(`Managed artifact is missing: ${artifact.path}`);
      continue;
    }
    if (artifact.kind === 'file') {
      if (sha256(content) !== artifact.sha256)
        errors.push(`Managed file checksum mismatch: ${artifact.path}`);
      continue;
    }
    if (artifact.kind === 'block') {
      const block = inspectManagedBlock(
        content,
        artifact.startMarker,
        artifact.endMarker,
      );
      if (
        block.startCount !== 1 ||
        block.endCount !== 1 ||
        block.block === null
      ) {
        errors.push(
          `Managed block markers are missing or duplicated: ${artifact.path}`,
        );
      } else if (sha256(block.block) !== artifact.sha256) {
        errors.push(`Managed block checksum mismatch: ${artifact.path}`);
      }
    }
  }

  for (const artifact of manifest.userOwnedArtifacts ?? []) {
    let absolutePath;
    try {
      absolutePath = resolveProjectPath(
        projectRoot,
        artifact.path,
        'user-owned artifact path',
      );
    } catch (error) {
      errors.push(`Unsafe user-owned artifact path: ${String(artifact.path)}`);
      continue;
    }
    if (!(await pathExists(absolutePath))) {
      errors.push(`User-owned override artifact is missing: ${artifact.path}`);
    }
  }

  const installedDnaPath = path.join(projectRoot, installedDnaRelativePath);
  if (await pathExists(installedDnaPath)) {
    try {
      const dna = await readJson(installedDnaPath);
      errors.push(
        ...(await validateDesignDna(dna, { requireAccepted: true })).map(
          (error) => `Design DNA: ${error}`,
        ),
      );
      if (sha256(jsonText(dna)) !== manifest.dna?.sha256)
        errors.push('Installed Design DNA does not match manifest DNA hash');
    } catch (error) {
      errors.push(`Cannot validate installed Design DNA: ${error.message}`);
    }
  }

  return {
    valid: errors.length === 0,
    projectRoot,
    documentId: manifest.dna?.documentId ?? null,
    revision: manifest.dna?.revision ?? null,
    managedArtifactCount: manifest.managedArtifacts?.length ?? 0,
    errors,
  };
}
