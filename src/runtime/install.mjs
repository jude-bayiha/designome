function safeCssComment(value) {
  return String(value)
    .replace(/\*\//gu, '* /')
    .replace(/[\r\n]+/gu, ' ');
}

function cssName(tokenId) {
  return tokenId
    .replace(/^token\./u, '')
    .replace(/[^a-zA-Z0-9-]+/gu, '-')
    .replace(/-+/gu, '-')
    .replace(/^-|-$/gu, '')
    .toLowerCase();
}

function cssValue(value, tokenId) {
  const rendered = String(value);
  if (
    /[;{}\r\n]/u.test(rendered) ||
    rendered.includes('/*') ||
    rendered.includes('*/')
  ) {
    throw new DesignomeError(`Unsafe literal CSS value in ${tokenId}`, {
      code: 'UNSAFE_CSS_TOKEN',
    });
  }
  return rendered;
}

function renderGeneratedCss(dna, scope, styling) {
  const exactTokens = [];
  const nonLiteralTokens = [];
  const generatedNames = new Set();
  for (const token of dna.tokens) {
    const generatedName = cssName(token.id);
    if (generatedNames.has(generatedName)) {
      throw new DesignomeError(`CSS token name collision for ${token.id}`, {
        code: 'CSS_TOKEN_COLLISION',
      });
    }
    generatedNames.add(generatedName);
    if (token.value?.kind === 'exact') {
      exactTokens.push(
        `    --designome-${generatedName}: ${cssValue(token.value.value, token.id)};`,
      );
    } else if (
      token.value?.kind === 'range' &&
      token.value.strategy === 'bounded' &&
      Number.isFinite(token.value.preferred)
    ) {
      exactTokens.push(
        `    --designome-${generatedName}: ${cssValue(`${token.value.preferred}${token.value.unit}`, token.id)};`,
      );
      nonLiteralTokens.push(
        `  /* ${safeCssComment(token.id)} bounds: ${token.value.minimum} to ${token.value.maximum} ${safeCssComment(token.value.unit)} */`,
      );
    } else {
      const explanation =
        token.value?.expression ??
        token.value?.reason ??
        (token.value?.kind === 'range'
          ? `${token.value.minimum} to ${token.value.maximum} ${token.value.unit}`
          : 'No literal CSS value is available.');
      nonLiteralTokens.push(
        `  /* ${safeCssComment(token.id)}: ${safeCssComment(explanation)} */`,
      );
    }
  }

  const lines = [
    `/* Generated by Designome from ${safeCssComment(dna.documentId)} revision ${dna.revision.number}. */`,
    '/* Do not edit this file. Put project-owned changes in designome.overrides.css. */',
    `/* Styling adapter: ${safeCssComment(styling.strategy)} (${safeCssComment(styling.system)} detected). */`,
    '',
    '@layer designome.tokens {',
    `  ${scope} {`,
    ...(exactTokens.length > 0
      ? exactTokens
      : ['    /* No exact token values were accepted. */']),
    '  }',
    ...(nonLiteralTokens.length > 0 ? ['', ...nonLiteralTokens] : []),
    '}',
    '',
  ];
  return lines.join('\n');
}

