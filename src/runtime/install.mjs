const manifestRelativePath = '.designome/manifest.json';
const installedDnaRelativePath = '.designome/design-dna.json';
const cssStartMarker = '/* designome:generated-import:start */';
const cssEndMarker = '/* designome:generated-import:end */';
const guidanceStartMarker = '<!-- designome:guidance:start -->';
const guidanceEndMarker = '<!-- designome:guidance:end -->';

const cssCandidates = [
  'src/app/globals.css',
  'app/globals.css',
  'src/styles/globals.css',
  'styles/globals.css',
  'src/index.css',
  'src/main.css',
];

function safeCssComment(value) {
  return String(value)
    .replace(/\*\//gu, '* /')
    .replace(/[\r\n]+/gu, ' ');
}

function cssName(tokenId) {
  return tokenId
    .replace(/^token\./u, '')
    .replace(/[^a-zA-Z0-9-]+/gu, '-')
    .replace(/-+/gu, '-')
    .replace(/^-|-$/gu, '')
    .toLowerCase();
}

function cssValue(value, tokenId) {
  const rendered = String(value);
  if (
    /[;{}\r\n]/u.test(rendered) ||
    rendered.includes('/*') ||
    rendered.includes('*/')
  ) {
    throw new DesignomeError(`Unsafe literal CSS value in ${tokenId}`, {
      code: 'UNSAFE_CSS_TOKEN',
    });
  }
  return rendered;
}

function renderGeneratedCss(dna, scope) {
  const exactTokens = [];
  const nonLiteralTokens = [];
  const generatedNames = new Set();
  for (const token of dna.tokens) {
    const generatedName = cssName(token.id);
    if (generatedNames.has(generatedName)) {
      throw new DesignomeError(`CSS token name collision for ${token.id}`, {
        code: 'CSS_TOKEN_COLLISION',
      });
    }
    generatedNames.add(generatedName);
    if (token.value?.kind === 'exact') {
      exactTokens.push(
        `    --designome-${generatedName}: ${cssValue(token.value.value, token.id)};`,
      );
    } else {
      const explanation =
        token.value?.expression ??
        token.value?.reason ??
        (token.value?.kind === 'range'
          ? `${token.value.minimum} to ${token.value.maximum} ${token.value.unit}`
          : 'No literal CSS value is available.');
      nonLiteralTokens.push(
        `  /* ${safeCssComment(token.id)}: ${safeCssComment(explanation)} */`,
      );
    }
  }

  const lines = [
    `/* Generated by Designome from ${safeCssComment(dna.documentId)} revision ${dna.revision.number}. */`,
    '/* Do not edit this file. Put project-owned changes in designome.overrides.css. */',
    '',
    '@layer designome.tokens {',
    `  ${scope} {`,
    ...(exactTokens.length > 0
      ? exactTokens
      : ['    /* No exact token values were accepted. */']),
    '  }',
    ...(nonLiteralTokens.length > 0 ? ['', ...nonLiteralTokens] : []),
    '}',
    '',
  ];
  return lines.join('\n');
}

function renderOverridesCss() {
  return [
    '/* Project-owned Designome overrides. This file is never overwritten. */',
    '@layer designome.overrides {',
    '  /* Add intentional local overrides here. */',
    '}',
    '',
  ].join('\n');
}

function renderCssImportBlock(generatedName, overridesName) {
  return [
    cssStartMarker,
    `@import "./${generatedName}";`,
    `@import "./${overridesName}";`,
    cssEndMarker,
    '',
  ].join('\n');
}

function renderGuidanceBlock() {
  return [
    guidanceStartMarker,
    '## Designome-generated UI',
    '',
    'Read `.designome/design-dna.json` and use `$designome-extract`, `$designome-install`, or `$designome-audit` as appropriate.',
    'Preserve claim status, use accepted generated tokens, cover applicable business states and stress cases, and audit generated UI before delivery.',
    guidanceEndMarker,
    '',
  ].join('\n');
}

async function assertProjectRoot(projectRoot) {
  const requested = path.resolve(projectRoot);
  const resolved = await fs.realpath(requested).catch(() => requested);
  const filesystemRoot = path.parse(resolved).root;
  if (resolved === filesystemRoot || resolved === path.resolve(os.homedir())) {
    throw new DesignomeError(
      'Refusing to use a broad filesystem or home directory as a target project',
      {
        code: 'UNSAFE_TARGET_PROJECT',
      },
    );
  }
  const stat = await fs.stat(resolved).catch(() => null);
  if (!stat?.isDirectory()) {
    throw new DesignomeError(`Target project is not a directory: ${resolved}`, {
      code: 'TARGET_PROJECT_MISSING',
    });
  }
  const markers = [
    '.git',
    'package.json',
    'pyproject.toml',
    'Cargo.toml',
    'composer.json',
  ];
  const hasMarker = (
    await Promise.all(
      markers.map((marker) => pathExists(path.join(resolved, marker))),
    )
  ).some(Boolean);
  if (!hasMarker) {
    throw new DesignomeError('Target path does not look like a project root', {
      code: 'INVALID_TARGET_PROJECT',
      details: [`Expected one of: ${markers.join(', ')}`],
    });
  }
  return resolved;
}

async function assertManagedDirectorySafe(projectRoot) {
  const managedDirectory = path.join(projectRoot, '.designome');
  if (!(await pathExists(managedDirectory))) return;
  const stat = await fs.stat(managedDirectory);
  if (!stat.isDirectory()) {
    throw new DesignomeError('.designome exists but is not a directory', {
      code: 'UNSAFE_MANAGED_DIRECTORY',
    });
  }
  const realManagedDirectory = await fs.realpath(managedDirectory);
  relativeInside(projectRoot, realManagedDirectory, '.designome directory');
}

async function resolveCssEntry(projectRoot, requestedEntry) {
  if (requestedEntry) {
    const candidate = resolveProjectPath(
      projectRoot,
      requestedEntry,
      '--css-entry',
    );
    if (!(await pathExists(candidate))) {
      throw new DesignomeError(`CSS entry does not exist: ${requestedEntry}`, {
        code: 'CSS_ENTRY_MISSING',
      });
    }
    const resolved = await fs.realpath(candidate);
    relativeInside(projectRoot, resolved, '--css-entry');
    const stat = await fs.stat(resolved);
    if (!stat.isFile()) {
      throw new DesignomeError(`CSS entry is not a file: ${requestedEntry}`, {
        code: 'INVALID_CSS_ENTRY',
      });
    }
    return resolved;
  }

  const matches = [];
  for (const candidate of cssCandidates) {
    const candidatePath = path.join(projectRoot, candidate);
    if (await pathExists(candidatePath)) {
      const resolvedCandidate = await fs.realpath(candidatePath);
      relativeInside(projectRoot, resolvedCandidate, 'discovered CSS entry');
      matches.push(resolvedCandidate);
    }
  }
  if (matches.length !== 1) {
    throw new DesignomeError(
      matches.length === 0
        ? 'No supported CSS entry was discovered; pass --css-entry'
        : 'Multiple CSS entries were discovered; pass --css-entry',
      {
        code: 'CSS_ENTRY_AMBIGUOUS',
        details: matches.map((match) =>
          toPosixPath(path.relative(projectRoot, match)),
        ),
      },
    );
  }
  return matches[0];
}

async function discoverInstructionFiles(projectRoot, cssEntryPath) {
  const results = [];
  const relativeDirectory = path.relative(
    projectRoot,
    path.dirname(cssEntryPath),
  );
  const segments =
    relativeDirectory === '' ? [] : relativeDirectory.split(path.sep);
  let current = projectRoot;
  for (const segment of ['', ...segments]) {
    if (segment) current = path.join(current, segment);
    for (const name of ['AGENTS.md', 'CLAUDE.md']) {
      const candidate = path.join(current, name);
      if ((await pathExists(candidate)) && !results.includes(candidate))
        results.push(candidate);
    }
  }
  return results.map((result) =>
    toPosixPath(path.relative(projectRoot, result)),
  );
}

function manifestArtifact(manifest, relativePath, kind) {
  return manifest?.managedArtifacts?.find(
    (artifact) => artifact.path === relativePath && artifact.kind === kind,
  );
}

async function inspectOwnedFile(
  projectRoot,
  relativePath,
  desiredContent,
  previousManifest,
) {
  const absolutePath = path.join(projectRoot, relativePath);
  const current = await readTextIfExists(absolutePath);
  const previous = manifestArtifact(previousManifest, relativePath, 'file');
  if (!previous && current !== null) {
    return {
      path: relativePath,
      kind: 'file',
      action: 'conflict',
      reason: 'Existing file is not owned by the manifest.',
    };
  }
  if (previous && current === null) {
    return {
      path: relativePath,
      kind: 'file',
      action: 'conflict',
      reason: 'Previously managed file is missing.',
    };
  }
  if (previous && sha256(current) !== previous.sha256) {
    return {
      path: relativePath,
      kind: 'file',
      action: 'conflict',
      reason: 'Managed file was modified outside Designome.',
    };
  }
  return {
    path: relativePath,
    kind: 'file',
    action:
      current === null
        ? 'create'
        : current === desiredContent
          ? 'unchanged'
          : 'update',
    content: desiredContent,
    sha256: sha256(desiredContent),
  };
}

async function inspectBlockFile({
  projectRoot,
  relativePath,
  desiredBlock,
  startMarker,
  endMarker,
  placement,
  previousManifest,
}) {
  const absolutePath = path.join(projectRoot, relativePath);
  const current = (await readTextIfExists(absolutePath)) ?? '';
  const inspection = inspectManagedBlock(current, startMarker, endMarker);
  const previous = manifestArtifact(previousManifest, relativePath, 'block');

  if (!previous && (inspection.startCount !== 0 || inspection.endCount !== 0)) {
    return {
      path: relativePath,
      kind: 'block',
      action: 'conflict',
      reason: 'Existing managed markers are not owned by the manifest.',
    };
  }
  if (previous) {
    if (
      inspection.startCount !== 1 ||
      inspection.endCount !== 1 ||
      inspection.block === null
    ) {
      return {
        path: relativePath,
        kind: 'block',
        action: 'conflict',
        reason: 'Managed markers are missing or duplicated.',
      };
    }
    if (sha256(inspection.block) !== previous.sha256) {
      return {
        path: relativePath,
        kind: 'block',
        action: 'conflict',
        reason: 'Managed block was modified outside Designome.',
      };
    }
  }

  let desiredContent;
  try {
    desiredContent = upsertManagedBlock(
      current,
      desiredBlock,
      startMarker,
      endMarker,
      { placement },
    );
  } catch (error) {
    return {
      path: relativePath,
      kind: 'block',
      action: 'conflict',
      reason: error.message,
    };
  }
  return {
    path: relativePath,
    kind: 'block',
    action:
      current === ''
        ? 'create'
        : current === desiredContent
          ? 'unchanged'
          : 'update',
    content: desiredContent,
    blockSha256: sha256(desiredBlock),
    startMarker,
    endMarker,
  };
}

